import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { copyFileSync, existsSync } from "node:fs";
import { isAbsolute, join } from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/`;

const prod = process.argv.includes("production");
// Development and verification never deploy implicitly.
const deploy = process.argv.includes("--deploy");

// Build artifacts stay in the repository unless deployment is explicitly requested.
// Set the destination locally; never commit a personal vault path.
const VAULT_PLUGIN = process.env.AI_ASSIST_VAULT_PLUGIN;
if (deploy && (!VAULT_PLUGIN || !isAbsolute(VAULT_PLUGIN) || !existsSync(VAULT_PLUGIN))) {
  throw new Error("Set AI_ASSIST_VAULT_PLUGIN to an existing absolute plugin directory before using --deploy.");
}

const copyToVault = {
  name: "copy-to-vault",
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length > 0) return;
      if (!deploy) return;
      for (const f of ["main.js", "manifest.json", "styles.css", "versions.json"]) {
        copyFileSync(f, join(VAULT_PLUGIN, f));
      }
      console.log("→ vault");
    });
  },
};

const buildOptions = {
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: ["obsidian", "electron", ...builtinModules, ...builtinModules.map((m) => `node:${m}`)],
  format: "cjs",
  target: "es2020",
  plugins: [copyToVault],
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
};

if (prod) {
  await esbuild.build(buildOptions);
} else {
  const ctx = await esbuild.context(buildOptions);
  await ctx.watch();
}
