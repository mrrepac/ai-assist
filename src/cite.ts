/*
 * Номера источников в тексте ответа.
 *
 * Поисковая модель ссылается прямо в строке: «родился в Москве[1][6][8]». В
 * длинном ответе такие хвосты стоят после каждой фразы и читать мешают, а
 * ответить на вопрос «откуда это» всё равно нечем: цифра указывает на место в
 * списке, который свёрнут под ответом. Поэтому из текста их убираем, а список
 * оставляем — он и есть то, ради чего поисковую модель берут.
 *
 * Отдельным модулем, а не в панели: чистка идёт по сырому markdown, и рядом
 * живут блоки кода и [[вики-ссылки]], где квадратная скобка значит своё. Здесь
 * это проверяется тестом, не поднимая ItemView.
 */
import { Source } from "./api";

/**
 * Куски, внутрь которых лезть нельзя: блоки кода и строчный код (там `[1]` —
 * индекс массива, а не источник) и [[вики-ссылки]] (правка внутри скобок рвёт
 * связи между заметками). Ловим их одним выражением с ОДНОЙ группой захвата,
 * чтобы `split` разложил текст на «трогать / не трогать» через одну.
 */
const SKIP = /(```[\s\S]*?```|~~~[\s\S]*?~~~|`[^`\n]*`|\[\[[^\]\n]*\]\])/g;

/**
 * Номер в квадратных скобках вместе с пробелом перед ним, если тот есть: без
 * этого «текст [1]. Дальше» превращалось бы в «текст . Дальше».
 *
 * Следом не должно быть `(`: `[1](адрес)` — готовая ссылка, и её текст сносить
 * нельзя. Идущие подряд `[1][6][8]` разбираются по одному, поэтому lookbehind
 * не нужен вовсе — а он и запрещён (iOS младше 16.4).
 */
const MARK = / ?\[(\d{1,3})\](?!\()/g;

/**
 * Убирает из текста ссылки-номера. Ответ без источников возвращается как есть:
 * `[1]` в обычном тексте — это просто число в скобках, и трогать его не за что.
 */
export function stripCitations(md: string, sources: Source[] | undefined): string {
  if (!sources?.length || !md.includes("[")) return md;

  const known = new Set(sources.map((s) => s.n));

  // Неприкосновенные куски стоят на нечётных местах — их пропускаем как есть.
  return md
    .split(SKIP)
    .map((part, i) =>
      i % 2 === 1
        ? part
        : part.replace(MARK, (whole, digits: string) =>
            // Номер, которого в списке нет, оставляем: модель ссылается и на
            // то, чего нам не прислали, но чужие числа в скобках сносить не за
            // что — это может быть и текст пользователя.
            known.has(Number(digits)) ? "" : whole,
          ),
    )
    .join("");
}
